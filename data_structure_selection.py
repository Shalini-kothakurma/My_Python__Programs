
# List
tasks = ["Study Python", "Practice coding", "Complete assignment"]

# Dictionary
student = {
    "name": "Ananya",
    "course": "Python",
    "email": "ananya@gmail.com"
}

# Tuple
screen_size = (1920, 1080)

# Set
course_tags = {"Python", "AI", "Python", "Programming"}


# Print each structure
print("List:", tasks)
print("Type:", type(tasks))

print("\nDictionary:", student)
print("Type:", type(student))

print("\nTuple:", screen_size)
print("Type:", type(screen_size))

print("\nSet:", course_tags)
print("Type:", type(course_tags))


